package io.github.tanvesh.explainer

import com.cloudbees.groovy.cps.NonCPS
import groovy.json.JsonOutput

/** Formats an Explanation for the console, the archived Markdown report, and chat webhooks. */
class Renderer implements Serializable {

    @NonCPS
    static String console(Explanation e) {
        StringBuilder sb = new StringBuilder()
        sb.append('\n========== BUILD FAILURE EXPLAINED ==========\n')
        sb.append("Category   : ${e.category}\n")
        if (e.failedStage) {
            sb.append("Stage      : ${e.failedStage}\n")
        }
        sb.append("Summary    : ${e.summary}\n")
        sb.append("Root cause : ${e.rootCause}\n")
        if (e.evidence) {
            sb.append("Evidence   : ${e.evidence}\n")
        }
        if (e.suggestedFixes) {
            sb.append('How to fix :\n')
            e.suggestedFixes.eachWithIndex { String f, int i -> sb.append("  ${i + 1}. ${f}\n") }
        }
        sb.append("Confidence : ${e.confidence}   Source: ${sourceLabel(e)}\n")
        if (e.llmError) {
            sb.append("LLM note   : ${e.llmError}\n")
        }
        sb.append('=============================================\n')
        return sb.toString()
    }

    @NonCPS
    static String markdown(Explanation e, Map buildInfo = [:]) {
        StringBuilder sb = new StringBuilder()
        sb.append("# Build failure: ${buildInfo?.jobName ?: 'job'} #${buildInfo?.buildNumber ?: '?'}\n\n")
        sb.append("**${e.summary}**\n\n")
        sb.append('| | |\n|---|---|\n')
        sb.append("| Category | `${e.category}` |\n")
        if (e.failedStage) {
            sb.append("| Failed stage | ${e.failedStage} |\n")
        }
        sb.append("| Confidence | ${e.confidence} |\n")
        sb.append("| Source | ${sourceLabel(e)} |\n")
        if (buildInfo?.buildUrl) {
            sb.append("| Build | ${buildInfo.buildUrl} |\n")
        }
        sb.append("\n## Root cause\n\n${e.rootCause}\n")
        if (e.evidence) {
            sb.append("\n## Evidence\n\n```\n${e.evidence}\n```\n")
        }
        if (e.suggestedFixes) {
            sb.append('\n## How to fix\n\n')
            e.suggestedFixes.eachWithIndex { String f, int i -> sb.append("${i + 1}. ${f}\n") }
        }
        if (e.llmError) {
            sb.append("\n> LLM was not used: ${e.llmError}\n")
        }
        sb.append("\n_Generated by jenkins-failure-explainer in ${e.durationMs} ms._\n")
        return sb.toString()
    }

    /** One-line text for build descriptions and short notifications. */
    @NonCPS
    static String oneLine(Explanation e) {
        String stage = e.failedStage ? " in '${e.failedStage}'" : ''
        return "[${e.category}]${stage}: ${e.summary}".toString()
    }

    /** Slack-style payload ({"text": ...}); also accepted by Mattermost, Rocket.Chat, Google Chat. */
    @NonCPS
    static String chatPayload(Explanation e, Map buildInfo = [:]) {
        StringBuilder t = new StringBuilder()
        t.append(":red_circle: *${buildInfo?.jobName ?: 'Build'} #${buildInfo?.buildNumber ?: '?'} failed*")
        if (e.failedStage) {
            t.append(" in stage *${e.failedStage}*")
        }
        t.append("\n*${e.summary}*\n${e.rootCause}\n")
        if (e.suggestedFixes) {
            t.append('*Try:*\n')
            e.suggestedFixes.take(3).each { t.append("• ${it}\n") }
        }
        if (buildInfo?.buildUrl) {
            t.append("<${buildInfo.buildUrl}console|Open console log>")
        }
        return JsonOutput.toJson([text: t.toString()])
    }

    @NonCPS
    static String json(Explanation e) {
        return JsonOutput.prettyPrint(JsonOutput.toJson(e.toMap()))
    }

    @NonCPS
    private static String sourceLabel(Explanation e) {
        switch (e.source) {
            case 'llm': return "LLM (${e.model})"
            case 'rules': return 'built-in rules'
            default: return 'none'
        }
    }
}
